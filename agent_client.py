"""Scoped transport for a Codex cloud task. Uses no model API or account tokens."""
import hashlib
import json
import os
from pathlib import Path
import re
import time
import urllib.error
import urllib.parse
import urllib.request

MAX_FILE = 20 * 1024 * 1024


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise RuntimeError("Room service redirected; refusing to forward credentials")


class RoomClient:
    def __init__(self, origin, token, *, allow_local_test=False):
        parsed = urllib.parse.urlsplit(origin)
        local = allow_local_test and parsed.hostname == "127.0.0.1"
        if (parsed.scheme != "https" and not local) or parsed.username or parsed.password or parsed.path not in ("", "/") or parsed.query or parsed.fragment:
            raise ValueError("Expected a fixed HTTPS service origin")
        self.origin = origin.rstrip("/")
        self.token = token
        self.expires = 0
        self.opener = urllib.request.build_opener(NoRedirect())

    def _request(self, path, *, data=None, raw=None, headers=None, limit=1024 * 1024):
        if not path.startswith("/agent/"):
            raise ValueError("Only room agent routes are allowed")
        actual = {"Authorization": "Bearer " + self.token, **(headers or {})}
        if data is not None:
            raw = json.dumps(data, ensure_ascii=False).encode()
            actual["Content-Type"] = "application/json"
        req = urllib.request.Request(self.origin + path, data=raw, headers=actual)
        with self.opener.open(req, timeout=25) as response:
            body = response.read(limit + 1)
            if len(body) > limit:
                raise ValueError("Response exceeds transport limit")
            if response.headers.get_content_type() == "application/json":
                return json.loads(body)
            return body

    def hello(self):
        response = self._request("/agent/hello", data={})
        self.expires = response["expires_at"] / 1000
        return {"title": response["title"], "expires_at": response["expires_at"]}

    def next_job(self, wait_for=120):
        if not self.expires:
            self.hello()
        deadline = min(time.time() + max(0, min(wait_for, 120)), self.expires)
        # Recover a lost claim response before requesting another piece of work.
        active = self._request("/agent/active")
        if active.get("job"):
            return active["job"]
        while time.time() < deadline:
            response = self._request("/agent/next?wait=20")
            if response.get("job"):
                return response["job"]
        return None

    def download(self, job, directory):
        destination = Path(directory)
        destination.mkdir(parents=True, exist_ok=True)
        result = []
        for file in job["files"]:
            if not re.fullmatch(r"[a-f0-9]{24}", file["id"]):
                raise ValueError("Invalid file ID")
            route = "/agent/jobs/{}/files/{}".format(job["id"], file["id"])
            raw = self._request(route, headers={"X-Lease": job["lease"]}, limit=MAX_FILE)
            if hashlib.sha256(raw).hexdigest() != file["sha256"]:
                raise ValueError("File checksum mismatch")
            path = destination / file["id"]
            # IDs are generated by the service; never use user filenames as paths.
            with path.open("wb") as stream:
                stream.write(raw)
            self._request(route + "/ack", data={"lease": job["lease"], "sha256": file["sha256"]})
            result.append({"path": str(path), "name": file["name"], "version": file["version"]})
        return result

    def artifact(self, job, path, name=None, mime="application/octet-stream"):
        source = Path(path)
        if source.stat().st_size > MAX_FILE:
            raise ValueError("Artifact exceeds 20 MB")
        return self._request("/agent/artifacts", raw=source.read_bytes(), headers={
            "X-Job-Id": job["id"], "X-Lease": job["lease"],
            "X-Filename": urllib.parse.quote(name or source.name, safe=""), "Content-Type": mime,
        })

    def finish(self, job, text, results_directory):
        directory = Path(results_directory)
        directory.mkdir(parents=True, exist_ok=True)
        payload = {"lease": job["lease"], "text": text}
        path = directory / (job["id"] + ".json")
        tmp = path.with_suffix(".tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as stream:
            json.dump(payload, stream, ensure_ascii=False)
        os.replace(tmp, path)
        return self._request("/agent/jobs/" + job["id"] + "/result", data=payload)

    def retry_result(self, job_id, results_directory):
        if not re.fullmatch(r"[a-f0-9]{24}", job_id):
            raise ValueError("Invalid job ID")
        payload = json.loads((Path(results_directory) / (job_id + ".json")).read_text())
        return self._request("/agent/jobs/" + job_id + "/result", data=payload)

    def error(self, job, message):
        return self._request("/agent/jobs/" + job["id"] + "/error", data={"lease": job["lease"], "error": message})
